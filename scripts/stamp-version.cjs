const { execSync } = require('child_process');
const fs = require('fs');
const path = require('path');

let sha = '';
let commitMsg = '';
try {
  sha = execSync('git rev-parse HEAD').toString().trim();
  commitMsg = execSync('git log -1 --pretty=%B').toString().trim().replace(/"/g, '\\"').replace(/\n/g, ' ');
} catch (e) {
  sha = 'build-' + Date.now();
  commitMsg = 'Latest app updates and improvements';
}

const targetPath = path.join(__dirname, '../src/constants/appVersion.ts');
const content = `// Auto-generated by scripts/stamp-version.cjs at build time
export const CURRENT_BUILD_SHA = "${sha}";
export const CURRENT_BUILD_DATE = "${new Date().toISOString()}";
export const GITHUB_REPO_OWNER = "mdrsr016-lgtm";
export const GITHUB_REPO_NAME = "Digital-Somity";
export const APK_DOWNLOAD_URL = "https://raw.githubusercontent.com/mdrsr016-lgtm/Digital-Somity/main/public/digitalsomity.apk";
`;

fs.writeFileSync(targetPath, content, 'utf8');
console.log('✓ Stamped app build SHA:', sha);

